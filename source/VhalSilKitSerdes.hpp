#pragma once

#include <string>
#include <utility>
#include <vector>

#include "silkit/util/Span.hpp"
#include "silkit/util/serdes/Deserializer.hpp"
#include "silkit/util/serdes/Serialization.hpp"
#include "silkit/util/serdes/Serializer.hpp"

// Wire-format helpers for the four VCDL methods exposed by VhalSilKitAdapter.
//
// The on-the-wire bytes match the SilAdapter-generated code exactly. Note that
// the generated TypeLib::Serializer::Serialize(...) emits the parameters as
// *bare* fields (no struct markers); the BeginStruct/EndStruct calls below are
// kept for clarity and are byte-equivalent, because SIL Kit's SerDes encodes
// BeginStruct as Align() and EndStruct as a no-op, both zero-width for these
// already byte-aligned fields (int32 bitSize=32, float, length-prefixed string).
// The layouts below therefore describe the actual generated bytes:
//
//   GetProperty(string name) -> int32
//     request : string(name)
//     response: int32(32)
//
//   SetProperty(string name, int32 value) -> void
//     request : string(name) . int32(32)
//     response: (empty)
//
//   GetPropertyFloat(string name) -> float
//     request : string(name)
//     response: float
//
//   SetPropertyFloat(string name, float value) -> void
//     request : string(name) . float
//     response: (empty)

namespace VhalSerDes {

inline std::vector<uint8_t> ToVector(SilKit::Util::Span<const uint8_t> span)
{
    return {span.begin(), span.end()};
}

// ---- Request deserializers ----

inline std::string DeserializeGetRequest(SilKit::Util::Span<const uint8_t> data)
{
    SilKit::Util::SerDes::Deserializer d{ToVector(data)};
    d.BeginStruct();
    auto name = d.Deserialize<std::string>();
    d.EndStruct();
    return name;
}

inline std::pair<std::string, int32_t> DeserializeSetInt32Request(SilKit::Util::Span<const uint8_t> data)
{
    SilKit::Util::SerDes::Deserializer d{ToVector(data)};
    d.BeginStruct();
    auto name = d.Deserialize<std::string>();
    auto value = d.Deserialize<int32_t>(32);
    d.EndStruct();
    return {std::move(name), value};
}

inline std::pair<std::string, float> DeserializeSetFloatRequest(SilKit::Util::Span<const uint8_t> data)
{
    SilKit::Util::SerDes::Deserializer d{ToVector(data)};
    d.BeginStruct();
    auto name = d.Deserialize<std::string>();
    auto value = d.Deserialize<float>();
    d.EndStruct();
    return {std::move(name), value};
}

// ---- Response serializers ----

inline std::vector<uint8_t> SerializeInt32Response(int32_t value)
{
    SilKit::Util::SerDes::Serializer s;
    s.BeginStruct();
    s.Serialize(value, 32);
    s.EndStruct();
    return s.ReleaseBuffer();
}

inline std::vector<uint8_t> SerializeFloatResponse(float value)
{
    SilKit::Util::SerDes::Serializer s;
    s.BeginStruct();
    s.Serialize(value);
    s.EndStruct();
    return s.ReleaseBuffer();
}

inline std::vector<uint8_t> SerializeVoidResponse()
{
    return {};
}

} // namespace VhalSerDes
